def export_dataset_files(base_dir: Path | None = None) -> list[str]:
    """Write every scenario's evidence to datasets/ as reusable artifacts."""
    base = Path(base_dir or (PROJECT_DIR / "datasets"))
    events_dir = base / "events"
    fs_dir = base / "filesystem"
    index_dir = base
    for path in (events_dir, fs_dir):
        path.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    index: list[dict] = []

    for scenario in SCENARIOS:
        index.append({
            "scenario": scenario.id,
            "name": scenario.name,
            "description": scenario.description,
            "expected_rules": scenario.expected_rules,
            "expected_chains": scenario.expected_chains,
            "expected_absent": scenario.expected_absent,
            "alternatives": scenario.alternatives,
            "notes": scenario.notes,
            "files": [s.filename for s in scenario.sources],
        })
        for source in scenario.sources:
            target_dir = fs_dir if source.file_type == "fsat" else events_dir
            target = target_dir / f"{scenario.id}_{source.filename}"
            all_rows = list(source.records) + list(source.invalid_records or [])
            if source.file_type == "fsat" and source.filename.lower().endswith(".csv"):
                import csv

                fieldnames: list[str] = []
                for row in all_rows:
                    for key in row:
                        if key not in fieldnames:
                            fieldnames.append(key)
                with open(target, "w", encoding="utf-8", newline="") as fh:
                    writer = csv.DictWriter(fh, fieldnames=fieldnames, restval="")
                    writer.writeheader()
                    writer.writerows(all_rows)
            else:
                payload = {
                    "synthetic": True,
                    "scenario": scenario.id,
                    "note": source.note,
                    "timezone_note": source.timezone_note,
                    "ground_truth": {
                        "expected_rules": scenario.expected_rules,
                        "expected_chains": scenario.expected_chains,
                        "expected_absent": scenario.expected_absent,
                        "benign_alternatives": scenario.alternatives,
                    },
                    "rejected_row_preview": source.errors,
                    "records": all_rows,
                }
                target.write_text(json.dumps(payload, indent=2), encoding="utf-8")
            written.append(str(target))

    (index_dir / "README.json").write_text(json.dumps({"scenarios": index}, indent=2),
                                           encoding="utf-8")
    written.append(str(index_dir / "README.json"))
    return written