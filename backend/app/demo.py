"""Demo data generation (explicitly labelled synthetic evidence).

Demonstration data is NEVER mixed with imported evidence: investigations,
evidence sources and events created here all carry `origin == "demo"` and are
rendered with a SYNTHETIC badge throughout the application.
"""

from __future__ import annotations

import json
from pathlib import Path

from sqlalchemy.orm import Session

from .config import PROJECT_DIR
from .datasets import SCENARIOS, Scenario, scenario_by_id
from .models import Investigation, new_id
from .services.detection import run_analysis
from .services.ingest import audit, ingest_file


def create_demo_investigation(db: Session, scenario: Scenario,
                              actor: str = "investigator", analyse: bool = True) -> Investigation:
    investigation = Investigation(
        id=new_id(),
        name=f"[SYNTHETIC] {scenario.name}",
        case_id=scenario.case_id,
        description=(
            f"{scenario.description}\n\n"
            "SYNTHETIC DEMO: every record in this investigation was generated by TRACE-X for "
            "demonstration and evaluation. Not real evidence."
        ),
        notes=(
            f"Scenario notes: {scenario.notes or 'none'}\n"
            f"Ground truth — expected rules: {', '.join(scenario.expected_rules) or 'none'}; "
            f"must not fire: {', '.join(scenario.expected_absent) or 'none'}; "
            f"expected chains: {', '.join(scenario.expected_chains) or 'none'}\n"
            f"Legitimate alternatives to consider: {'; '.join(scenario.alternatives)}"
        ),
        status="open",
        origin="demo",
        analysis_config={},
    )
    db.add(investigation)
    db.flush()

    for source in scenario.sources:
        payload = _source_payload(scenario, source)
        # Synthetic evidence goes through the SAME parser, validation, hashing and
        # audit path as a real upload — the demo is generated evidence, not a
        # shortcut around ingestion.
        ingest_file(
            db, investigation, filename=source.filename, content=payload,
            file_type=source.file_type, origin="demo", actor=actor,
        )
    db.flush()
    audit(db, "demo.investigation_created", investigation.id, actor,
          detail={"scenario": scenario.id, "case_id": scenario.case_id,
                  "sources": len(scenario.sources)})
    db.commit()

    if analyse:
        run_analysis(db, investigation, actor=actor, trigger="demo")
        db.refresh(investigation)
    return investigation


def _source_payload(scenario: Scenario, source) -> bytes:
    """Serialize a scenario source into the bytes a real import would receive."""
    if source.file_type == "fsat":
        rows = list(source.records) + list(source.invalid_records or [])
        if source.filename.lower().endswith(".csv"):
            import csv
            import io

            if not rows:
                raise ValueError("fsat CSV source has no rows")
            fieldnames: list[str] = []
            for row in rows:
                for key in row:
                    if key not in fieldnames:
                        fieldnames.append(key)
            buffer = io.StringIO()
            writer = csv.DictWriter(buffer, fieldnames=fieldnames, restval="")
            writer.writeheader()
            writer.writerows(rows)
            return buffer.getvalue().encode("utf-8")
        return json.dumps(rows, indent=2).encode("utf-8")

    payload = {
        "synthetic": True,
        "scenario": scenario.id,
        "scenario_name": scenario.name,
        "note": source.note,
        "timezone_note": source.timezone_note,
        "ground_truth": {
            "expected_rules": scenario.expected_rules,
            "expected_absent": scenario.expected_absent,
            "expected_chains": scenario.expected_chains,
            "benign_alternatives": scenario.alternatives,
        },
        "records": list(source.records) + list(source.invalid_records or []),
    }
    return json.dumps(payload, indent=2).encode("utf-8")


def create_demo_set(db: Session, scenario_ids: list[str] | None = None,
                    actor: str = "investigator") -> list[dict]:
    selected = []
    for sid in (scenario_ids or [s.id for s in SCENARIOS]):
        scenario = scenario_by_id(sid)
        if scenario is None:
            continue
        selected.append(create_demo_investigation(db, scenario, actor=actor))
    return [
        {
            "id": inv.id, "name": inv.name, "case_id": inv.case_id, "origin": inv.origin,
            "status": inv.status,
        }
        for inv in selected
    ]


def demo_summary(db: Session) -> dict:
    invs = db.query(Investigation).filter(Investigation.origin == "demo").all()
    return {
        "demo_investigations": len(invs),
        "available_scenarios": [s.id for s in SCENARIOS],
        "labeling": (
            "Demo records are stored with origin='demo' on the investigation, evidence source "
            "and every event, and are never merged into an imported investigation."
        ),
    }


